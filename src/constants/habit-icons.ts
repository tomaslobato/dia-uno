const iconIndex = new Map<string, HabitIconEntry>();
for (const category of HABIT_ICON_CATEGORIES) {
  for (const icon of category.icons) iconIndex.set(icon.name, icon);
}

export function isHabitIconName(value: unknown): value is HabitIconName {
  return typeof value === 'string' && iconIndex.has(value);
}

export function searchHabitIcons(query: string): HabitIconEntry[] {
  const normalized = query.trim().toLowerCase().normalize('NFD').replace(/\p{M}/gu, '');
  if (!normalized) return HABIT_ICON_CATEGORIES.flatMap((category) => category.icons);
  return HABIT_ICON_CATEGORIES.flatMap((category) => category.icons).filter((icon) => {
    const haystack = [icon.name, ...icon.keywords].join(' ').toLowerCase().normalize('NFD').replace(/\p{M}/gu, '');
    return haystack.includes(normalized);
  });
}

export function searchHabitEmojis(query: string): string[] {
  const normalized = query.trim();
  if (!normalized) return HABIT_EMOJIS;
  return HABIT_EMOJIS.filter((emoji) => emoji.includes(normalized));
}
